// Copies badge names and tiers into the send-emails function, which can't import from src/.
import { writeFileSync } from 'node:fs'
import { BADGE_DEFS, MONTHLY_DEFS } from '../src/features/badges/definitions.ts'

const all = { ...BADGE_DEFS, ...MONTHLY_DEFS }
const rows = Object.entries(all)
  .map(([key, d]) => `  ${JSON.stringify(key)}: { name: ${JSON.stringify(d.name)}, tier: ${JSON.stringify(d.tier)}, for: ${JSON.stringify(d.for)} },`)
  .join('\n')
writeFileSync(
  new URL('../supabase/functions/_shared/badges.ts', import.meta.url),
  `// Generated by scripts/sync-email-badges.mjs from src/features/badges/definitions.ts. Re-run after renaming a badge.\nexport const BADGES: Record<string, { name: string; tier: 'week' | 'month' | 'year' | 'cup'; for: string }> = {\n${rows}\n}\n`,
)
